-- Индексы, которых Prisma не умеет объявлять в schema.prisma.
--
-- Единственный источник правды для таких объектов. Миграции применяют их на
-- проде, но CI и локальная тестовая база поднимаются через `prisma db push`,
-- а он строит схему по schema.prisma — то есть всё, чего в схеме быть не
-- может, там просто не появляется.
--
-- Так уже потерялась уникальность заявки на район: гарантия «одна открытая
-- заявка» держалась только на индексе, в CI индекса не было, и второй клан
-- спокойно подавал вторую заявку. Файл применяется скриптом apply-raw-indexes
-- сразу после db push.
--
-- Все операторы обязаны быть идемпотентными.

-- Одна открытая заявка на район. Два клана, подавших заявку одновременно,
-- оба увидят «открытых нет» — от гонки спасает только база.
CREATE UNIQUE INDEX IF NOT EXISTS "territory_claims_one_open_per_territory"
  ON "territory_claims" ("territory_id")
  WHERE "status" IN ('PENDING', 'BATTLE');
