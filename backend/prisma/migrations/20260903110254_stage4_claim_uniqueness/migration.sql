-- Одна открытая заявка на район.
--
-- Проверять это чтением нельзя: два клана, подавших заявку одновременно,
-- оба увидят «открытых нет» и оба вставят строку. Частичный уникальный
-- индекс роняет вторую вставку на уровне базы, и сервис ловит P2002.
--
-- Prisma не умеет частичные уникальные индексы декларативно, поэтому он
-- живёт только здесь; в schema.prisma его нет и быть не может.
CREATE UNIQUE INDEX IF NOT EXISTS "territory_claims_one_open_per_territory"
  ON "territory_claims" ("territory_id")
  WHERE "status" IN ('PENDING', 'BATTLE');
