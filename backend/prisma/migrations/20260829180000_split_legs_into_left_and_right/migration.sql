-- Ноги разделены на левую и правую.
--
-- До этого на обе ноги приходилась одна зона LEGS, тогда как руки уже
-- были разведены на LEFT_ARM и RIGHT_ARM. Макет боевого экрана рисует
-- ноги двумя ячейками — слои «ЗБ Нога Л» и «ЗБ Нога П», — то есть
-- задумана та же пара, что у рук.
--
-- Миграция аддитивная: LEGS не удаляется. На нём лежат уже сыгранные
-- бои (battle_turns.zone), и убрать значение enum значило бы сломать
-- чтение истории. Новые бои им не пользуются.
ALTER TYPE "BodyZone" ADD VALUE IF NOT EXISTS 'RIGHT_LEG';
ALTER TYPE "BodyZone" ADD VALUE IF NOT EXISTS 'LEFT_LEG';
