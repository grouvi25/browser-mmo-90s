-- Перевод боевого опыта на кривую «Ревизия 2» (книга заказчика 23.10).
--
-- Новая таблица уровней: 15 уровней, пороги
--   0 / 883 / 2 625 / 6 599 / 15 482 / 34 982 / 77 180 / 167 499 /
--   359 161 / 763 085 / 1 609 550 / 3 375 101 / 7 043 101 /
--   14 637 717 / 30 316 376
-- Прежняя кривая GanjaWars (31 уровень до 30 000 XP) заменена.
--
-- Персонажи сохраняют достигнутый уровень: накопленный опыт переводится
-- пропорционально прогрессу внутри текущего уровня (доля пути до
-- следующего уровня по старой шкале переносится в новую шкалу).
-- Уровни выше 15-го (таких пока нет) прижимаются к 15-му.

WITH old_t(lvl, need) AS (
  VALUES (1,0),(2,5),(3,15),(4,37),(5,76),(6,143),(7,240),(8,370),(9,535),
         (10,740),(11,1000),(12,1310),(13,1680),(14,2120),(15,2640),
         (16,3250),(17,3960),(18,4780),(19,5720),(20,6790),(21,8000),
         (22,9360),(23,10880),(24,12570),(25,14440),(26,16500),(27,18760),
         (28,21230),(29,23920),(30,26840),(31,30000)
), new_t(lvl, need) AS (
  VALUES (1,0),(2,883),(3,2625),(4,6599),(5,15482),(6,34982),(7,77180),
         (8,167499),(9,359161),(10,763085),(11,1609550),(12,3375101),
         (13,7043101),(14,14637717),(15,30316376)
), scaled AS (
  SELECT c.id,
         c.battle_level AS lvl,
         GREATEST(0.0, LEAST(1.0,
           (CAST(c.battle_exp AS double precision) - o.need)
           / NULLIF(o2.need - o.need, 0))) AS frac,
         n.need AS n_from, n2.need AS n_to
  FROM characters c
  JOIN old_t o  ON o.lvl  = c.battle_level
  JOIN old_t o2 ON o2.lvl = c.battle_level + 1
  JOIN new_t n  ON n.lvl  = c.battle_level
  JOIN new_t n2 ON n2.lvl = c.battle_level + 1
  WHERE c.battle_level < 15
)
UPDATE characters c
SET battle_exp = GREATEST(0, FLOOR(s.n_from + s.frac * (s.n_to - s.n_from))::int)
FROM scaled s
WHERE c.id = s.id;

-- 15-й уровень — последний: следующего порога нет, долю пути переносить
-- некуда. Ставим ровно на порог 15-го: без этого старый опыт (тысячи)
-- при пороге 30 млн опустил бы персонажа уровня до 2-го при пересчёте.
-- Сюда же — гипотетические персонажи выше 15-го.
UPDATE characters SET battle_exp = 30316376 WHERE battle_level >= 15;
UPDATE characters SET battle_level = 15 WHERE battle_level > 15;
