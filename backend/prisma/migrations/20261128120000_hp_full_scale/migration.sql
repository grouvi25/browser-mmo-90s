-- 28.11: урон проходит полностью, поэтому всё здоровье выросло в 100/35 раза
-- (формула справочника та же, в коде умножается на HP_SCALE). Переводим
-- сохранённые максимум и текущее здоровье персонажей в новую шкалу.
UPDATE "characters"
SET "hp_max" = ROUND("hp_max" * 100.0 / 35)::int,
    "hp_current" = LEAST(ROUND("hp_current" * 100.0 / 35)::int, ROUND("hp_max" * 100.0 / 35)::int);
