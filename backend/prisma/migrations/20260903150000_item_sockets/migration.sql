-- Гнёзда под камни у экземпляра вещи.
--
-- Макет инвентаря рисует под каждой ячейкой снаряжения по два мелких
-- гнезда, а панель улучшений — «Государственная вставка камней» —
-- складывает вставку из вещи, камня и огранки. Гнездо и есть то, куда
-- эта пара ложится.
--
-- Хранится массивом в JSON, а не таблицей: гнёзд у вещи два, читаются
-- они всегда вместе с самой вещью и по отдельности никогда не
-- ищутся. Форма — [{ "stone": "stone_grade_2", "cut": "cut_damage" }].
--
-- Столбец допускает NULL: у всех уже созданных вещей гнёзда пусты, и
-- отдельного заполнения это не требует.
ALTER TABLE "item_instances" ADD COLUMN "sockets_json" JSONB;

-- Запись в журнал вещей о вставке камня. Значение добавляется,
-- ничего не удаляется: на старых значениях висят уже записанные
-- журналы.
ALTER TYPE "ItemLogAction" ADD VALUE IF NOT EXISTS 'SOCKET_INSERTED';
