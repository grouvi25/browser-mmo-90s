import { expect, test } from '@playwright/test'

test('новичок покупает и настраивает оружие в городе, потом видит письмо', async ({ page, request, isMobile }) => {
  const login = 'guide_' + Date.now().toString(36) + Math.random().toString(36).slice(2, 6)
  const password = 'visual_pass_123'
  const register = await request.post('/api/auth/register', {
    data: { login, password, email: login + '@visual.local', acceptPolicy: true, acceptPd: true },
  })
  expect(register.status()).toBe(201)
  const session = await request.post('/api/auth/login', { data: { login, password } })
  expect(session.status()).toBe(200)
  const { token, userId } = await session.json() as { token: string; userId: string }
  await page.addInitScript(({ token, userId, login }) => {
    localStorage.setItem('mmo_token', token)
    localStorage.setItem('mmo_user', JSON.stringify({ userId, login }))
  }, { token, userId, login })

  await page.goto('/character/create')
  await page.getByRole('button', { name: /Студент/ }).click()
  await page.getByRole('button', { name: 'Создать персонажа' }).click()
  await expect(page).toHaveURL(/\/$/)
  const guide = page.getByRole('complementary', { name: 'Обучение в городе' })
  const letter = page.getByRole('dialog', { name: /Кодекс выживания/ })
  await expect(guide.getByText('Купи оружие')).toBeVisible()
  await expect(letter).toHaveCount(0)
  await guide.getByRole('link', { name: 'В Госмагазин' }).click()
  const buy = page.locator('[data-tutorial-focus]').getByText('Купить', { exact: true })
  await expect(buy).toBeVisible()
  await expect(page.locator('.gshop-card').filter({ has: buy })).toContainText('7–15,75 HP')
  await buy.click()
  await expect(guide.getByText('Надень оружие')).toBeVisible()
  await guide.getByRole('link', { name: 'На Склад' }).click()
  await page.reload()
  const equip = page.locator('[data-tutorial-focus]').getByText('Надеть', { exact: true })
  await expect(equip).toBeVisible()
  await equip.click()

  await expect(guide.getByText('Вложи очко в урон')).toBeVisible()
  await page.locator('[data-tutorial-focus]').getByText('Настроить', { exact: true }).click()
  const settings = page.locator('.inv-setup')
  await expect(settings.getByRole('spinbutton', { name: /Макс. урон/ })).toHaveAttribute('data-tutorial-focus')
  await settings.getByRole('spinbutton', { name: /Макс. урон/ }).fill('1')
  await settings.getByRole('button', { name: 'Сохранить' }).click()
  await guide.getByRole('link', { name: 'К характеристикам' }).click()
  const plus = page.getByRole('button', { name: '+1 Сила', exact: true })
  await expect(plus).toBeEnabled()
  if (isMobile) await plus.tap()
  else await plus.click()
  const savedStats = page.waitForResponse(response => response.url().endsWith('/api/characters/stats/apply')
    && response.request().method() === 'POST')
  await page.getByRole('button', { name: 'Подтвердить', exact: true }).click()
  expect((await savedStats).ok()).toBe(true)
  await expect(letter).toHaveCount(0)
  await guide.getByRole('button', { name: 'Завершить обучение' }).click()
  await expect(letter).toBeVisible()
  await expect(letter).toContainText(login)
  await letter.getByRole('button', { name: 'Понял, Бывалый' }).click()
  await expect(letter).toHaveCount(0)
  await page.reload()
  await expect(guide).toHaveCount(0)
  await expect(letter).toHaveCount(0)
})
