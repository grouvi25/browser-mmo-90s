// =============================================================
// Мелочи оформления эфира: время в ленте и цвет уровня в списке
// онлайна. Живут отдельно от компонентов намеренно — их зовут из
// четырёх мест, и держать их рядом с разметкой значит тащить за
// собой весь виджет ради одной функции.
// =============================================================

/**
 * Час и минута отправки — по Москве у всех игроков (обращение №37):
 * раньше время бралось с устройства, и о времени события в чате
 * игроки из разных поясов договаривались вслепую.
 */
const MSK = new Intl.DateTimeFormat('ru-RU', { timeZone: 'Europe/Moscow', hour: '2-digit', minute: '2-digit', hourCycle: 'h23' })
export function chatTime(iso: string): string {
  return MSK.format(new Date(iso))
}

/**
 * Цвет уровня в списке онлайна. В макете он ничего не значит —
 * оформление, — но разнобой там нарисован, поэтому держим три ступени.
 */
export function levelTone(level: number): 'r' | 'c' | 'o' {
  if (level >= 25) return 'c'
  if (level >= 10) return 'r'
  return 'o'
}
