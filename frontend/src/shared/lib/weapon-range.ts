// Дальность оружия в клетках поля боя (правка заказчика 22.10: «у оружия,
// если это дистанционное, должно быть количество клеток выставлено»).
// Ближнее оружие бьёт только соседнюю клетку.
export function rangeLabel(cells: number): string {
  if (cells <= 1) return 'вплотную (1 клетка)'
  const mod10 = cells % 10, mod100 = cells % 100
  const word = mod10 === 1 && mod100 !== 11 ? 'клетка' : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14) ? 'клетки' : 'клеток'
  return `${cells} ${word}`
}
