const CYRILLIC = /[а-яё]/i

/** Текст ошибки для игрока: русский от сервера оставляем как есть,
 *  английский заменяем по коду, незнакомый — общей фразой. */
export function playerErrorMessage(code: string, serverMessage: string): string {
  if (CYRILLIC.test(serverMessage)) return serverMessage
  return RU[code] ?? 'Не получилось, попробуйте ещё раз'
}
